"""Refresh lock files from the verified runtime and build environments; no installs."""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
tools = ROOT / ".local" / "build-tools"
if tools.is_dir():
    sys.path.insert(0, str(tools))
from dependency_tools import dependency_closure, requirement_lines


def write_lock(path, distributions, prefix=""):
    lines = ["# Windows x64; Python 3.12 / 3.14. Generated by scripts/lock_dependencies.py."]
    if prefix:
        lines.append(prefix)
    lines.extend(f"{name}=={distribution.version}" for name, distribution in sorted(distributions.items()))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    runtime = dependency_closure(requirement_lines(ROOT / "requirements.txt"))
    build = dependency_closure(requirement_lines(ROOT / "requirements-build.txt"))
    write_lock(ROOT / "requirements-lock.txt", runtime)
    write_lock(ROOT / "requirements-build-lock.txt",
               {name: distribution for name, distribution in build.items() if name not in runtime},
               "-r requirements-lock.txt")
    print(f"Locked {len(runtime)} runtime and {len(build)} build distributions; no packages installed.")


if __name__ == "__main__":
    main()
