"""Validate or refresh Windows locks from installed packages; never install."""

import argparse
import sys
from pathlib import Path

if __package__:
    from .dependency_tools import dependency_closure, enable_build_tools, requirement_lines, validate_lock
else:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from dependency_tools import dependency_closure, enable_build_tools, requirement_lines, validate_lock

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Windows x64; Python 3.12 / 3.14. Generated by scripts/lock_dependencies.py."


def lock_text(distributions, prefix=""):
    lines = [HEADER]
    if prefix:
        lines.append(prefix)
    lines.extend(f"{name}=={distribution.version}" for name, distribution in sorted(distributions.items()))
    return "\n".join(lines) + "\n"


def write_lock(path, distributions, prefix=""):
    Path(path).write_text(lock_text(distributions, prefix), encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate existing locks without writing files")
    args = parser.parse_args(argv)
    enable_build_tools()
    if args.check:
        runtime = validate_lock(ROOT / "requirements-lock.txt")
        build = validate_lock(ROOT / "requirements-build-lock.txt")
        expected_runtime = dependency_closure(requirement_lines(ROOT / "requirements.txt"))
        expected_build = dependency_closure(requirement_lines(ROOT / "requirements-build.txt"))
        if runtime.keys() != expected_runtime.keys() or build.keys() != (expected_runtime.keys() | expected_build.keys()):
            raise RuntimeError("Lock contents differ from the declared runtime/build dependency closures")
        print(f"Locks verified: {len(runtime)} runtime, {len(build) - len(runtime)} additional build distributions.")
        return 0
    runtime = dependency_closure(requirement_lines(ROOT / "requirements.txt"))
    build = dependency_closure(requirement_lines(ROOT / "requirements-build.txt"))
    # Resolve everything before touching either lock.
    write_lock(ROOT / "requirements-lock.txt", runtime)
    write_lock(
        ROOT / "requirements-build-lock.txt",
        {name: distribution for name, distribution in build.items() if name not in runtime},
        "-r requirements-lock.txt",
    )
    print(f"Locked {len(runtime)} runtime and {len(build)} build distributions; no packages installed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
